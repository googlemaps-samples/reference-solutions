function createLotPolygon(
  lat: number,
  lng: number,
  halfWidthDeg: number,
  halfHeightDeg: number,
  tiltDeg = 0
): { lat: number; lng: number }[] {
  const rad = (tiltDeg * Math.PI) / 180;
  const cos = Math.cos(rad);
  const sin = Math.sin(rad);

  const corners = [
    { x: -halfWidthDeg, y: halfHeightDeg },
    { x: halfWidthDeg, y: halfHeightDeg },
    { x: halfWidthDeg, y: -halfHeightDeg },
    { x: -halfWidthDeg, y: -halfHeightDeg },
  ];

  return corners.map(({ x, y }) => ({
    lat: Number((lat + (y * cos - x * sin)).toFixed(6)),
    lng: Number((lng + (x * cos + y * sin)).toFixed(6)),
  }));
}

