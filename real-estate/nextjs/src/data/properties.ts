import type { LatLngPoint, PropertyListing } from '@/types/real-estate';

/**
 * Generates a realistic rectangular San Francisco cadastral lot footprint
 * around a center coordinate, with optional slight rotation to align with
 * SF's street grids (e.g., North-South grid vs. South of Market 45° grid).
 */
function createParcelLot(
  centerLat: number,
  centerLng: number,
  widthMeters: number,
  depthMeters: number,
  rotationDeg = 0
): LatLngPoint[] {
  const metersPerLat = 111320;
  const metersPerLng = 111320 * Math.cos((centerLat * Math.PI) / 180);
  const rad = (rotationDeg * Math.PI) / 180;
  const cos = Math.cos(rad);
  const sin = Math.sin(rad);

  const halfW = widthMeters / 2;
  const halfD = depthMeters / 2;

  const corners: [number, number][] = [
    [-halfW, -halfD],
    [halfW, -halfD],
    [halfW, halfD],
    [-halfW, halfD],
  ];

  return corners.map(([dx, dy]) => {
    const rx = dx * cos - dy * sin;
    const ry = dx * sin + dy * cos;
    return {
      lat: Number((centerLat + ry / metersPerLat).toFixed(7)),
      lng: Number((centerLng + rx / metersPerLng).toFixed(7)),
    };
  });
}

