import { LatLngPoint, PropertyListing } from '../models/real-estate.models';

function buildParcelRect(
  lat: number,
  lng: number,
  widthMeters: number,
  depthMeters: number,
  angleDeg = 0
): LatLngPoint[] {
  const metersPerDegLat = 111320;
  const metersPerDegLng = 111320 * Math.cos((lat * Math.PI) / 180);
  const halfW = widthMeters / 2;
  const halfD = depthMeters / 2;
  const rad = (angleDeg * Math.PI) / 180;
  const cos = Math.cos(rad);
  const sin = Math.sin(rad);

  const corners: [number, number][] = [
    [-halfW, -halfD],
    [halfW, -halfD],
    [halfW, halfD],
    [-halfW, halfD],
  ];

  return corners.map(([x, y]) => {
    const rx = x * cos - y * sin;
    const ry = x * sin + y * cos;
    return {
      lat: Number((lat + ry / metersPerDegLat).toFixed(6)),
      lng: Number((lng + rx / metersPerDegLng).toFixed(6)),
    };
  });
}

